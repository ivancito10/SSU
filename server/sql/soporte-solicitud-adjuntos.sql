CREATE TABLE administracion.soporte_solicitud_adjuntos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud INTEGER NOT NULL,
    nombre_archivo VARCHAR(255) NOT NULL,
    ruta_url TEXT NOT NULL,
    tipo_mime VARCHAR(120) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_soporte_solicitud_adjuntos_solicitud
        FOREIGN KEY (id_solicitud)
        REFERENCES administracion.soporte_solicitudes (id)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

CREATE INDEX idx_soporte_solicitud_adjuntos_solicitud
    ON administracion.soporte_solicitud_adjuntos (id_solicitud);
