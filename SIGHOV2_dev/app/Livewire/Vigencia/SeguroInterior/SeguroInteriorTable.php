                </svg>')
                ->class('btn btn-green')
                ->tooltip('ASIGNAR USUARIO RESPONSABLE')
                ->dispatchTo('vigencia.seguro-interior.seguro-interior-main', 'asignar_usuario_responsable', ['rowId' => $row->id])
