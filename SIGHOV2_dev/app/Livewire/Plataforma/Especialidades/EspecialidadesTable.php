                ->id()
                ->class('btn btn-green')
                ->tooltip('HABILITAR ESPECIALIDAD')
                ->dispatchTo('plataforma.especialidades.especialidades-main', 'cambiarEstado', ['data' => $row->id])
                ->can(allowed: auth()->user()->can('habilitar.especialidades'));
        }
        return $buttons;
    }
}
